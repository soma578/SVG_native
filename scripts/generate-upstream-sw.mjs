#!/usr/bin/env node
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const gasCsvUrl = 'https://script.google.com/macros/s/AKfycbyAD-xMVje_lJL7452V7wdcMv15bphid722XzmLHwakuDT0ZeHd4SV83y5ezzdp6FTQ/exec'

const walk = (directory, base = root) => {
  const files = []
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (['.git', '.next', 'node_modules', 'public', '.submodule-git-backup'].includes(entry.name)) continue
    const target = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...walk(target, base))
    else if (entry.isFile() || entry.isSymbolicLink()) files.push(path.relative(base, target).split(path.sep).join('/'))
  }
  return files
}

const isShellAsset = (relative) => {
  if (relative === 'index.html') return true
  if (relative === 'svgmapAppLayers/Container.svg') return true
  if (relative.startsWith('svgmapjs/') && /\.(js|html)$/.test(relative)) return true
  if (relative.startsWith('svgmapAppLayers/basemaps/')) return /\.(js|html|svg)$/.test(relative)
  if (relative.startsWith('svgmapAppLayers/authoringLayers/local/csvLayer/')) {
    return /\.(js|html|xhtml|svg|css|png)$/.test(relative) && !relative.endsWith('.test.mjs')
  }
  if (relative.startsWith('svgmapAppLayers/appLayers/oxygenDeviceLog/')) {
    return /\.(js|html|svg|csv)$/.test(relative)
  }
  if (relative.startsWith('svgmapAppLayers/appLayers/chugokuOutages/')) {
    return /\.(js|html|svg)$/.test(relative)
  }
  if (relative.startsWith('svgmapAppLayers/appLayers/okayamaLandslideCandidates/')) {
    if (relative.includes('/geometry/') || relative.endsWith('/candidates.json')) return false
    return /\.(js|html|svg)$/.test(relative)
  }
  if (!relative.startsWith('svgmapAppLayers/appLayers/svg3-bosai/')) return false
  if (/\/map\/data\//.test(relative)) return false
  if (/\/hazard\/(pref|districts)\//.test(relative)) return false
  if (/\/hazard-overview\//.test(relative)) return false
  if (/\/hazard-vector-overview\//.test(relative)) return false
  if (/\/hazard-raster-tiles\//.test(relative)) return false
  if (/\/hazard-city-bundles\//.test(relative)) return false
  return /\.(js|html|svg|json)$/.test(relative)
}

const sourceFiles = walk(root).filter(isShellAsset).sort()
const hash = crypto.createHash('sha256')
hash.update(fs.readFileSync(fileURLToPath(import.meta.url)))
hash.update(fs.readFileSync(path.join(root, 'scripts/prepare-public-assets.mjs')))
hash.update(fs.readFileSync(path.join(root, 'scripts/prepare-hazard-transition.mjs')))
hash.update(fs.readFileSync(path.join(root, 'scripts/prepare-hazard-raster-lod.mjs')))
hash.update(fs.readFileSync(path.join(root, 'scripts/prepare-hazard-city-bundles.mjs')))
hash.update(fs.readFileSync(path.join(root, 'scripts/generate-hazard-detail-tiles.mjs')))
hash.update(fs.readFileSync(path.join(root, 'scripts/hazard-detail-style.mjs')))
hash.update(fs.readFileSync(path.join(root, 'svgmapAppLayers/appLayers/svg3-bosai/hazard-raster-tiles/index.json')))
hash.update(fs.readFileSync(path.join(root, 'svgmapAppLayers/appLayers/svg3-bosai/hazard-detail-tiles/index.json')))
for (const relative of sourceFiles) {
  hash.update(relative)
  hash.update(fs.readFileSync(path.join(root, relative)))
}
for (const relative of [
  'public/layerListStyle.css',
  'public/svgmap-bootstrap.js',
  'public/customShowPoiProperty.js',
]) {
  hash.update(relative)
  hash.update(fs.readFileSync(path.join(root, relative)))
}
const version = hash.digest('hex').slice(0, 12)
const sw = `// Generated by scripts/generate-upstream-sw.mjs. Do not edit directly.
// Cache only explicit data and map tiles. Application code always uses the network.
const VERSION = '${version}';
const DYNAMIC_CACHE = 'svgmap-dynamic-v2';
const TILE_CACHE = 'svgmap-tiles-v2';
const META_CACHE = 'svgmap-cache-meta-v1';
const GAS_CSV_URL = ${JSON.stringify(gasCsvUrl)};
const MAX_DYNAMIC_ENTRIES = 50;
const MAX_TILE_ENTRIES = 1500;

const notifyClients = (message) => self.clients.matchAll({ type: 'window', includeUncontrolled: true })
  .then((clients) => clients.forEach((client) => client.postMessage(message)));

const trimEntries = async (cacheName, maximum) => {
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  const expired = keys.slice(0, Math.max(0, keys.length - maximum));
  const meta = await caches.open(META_CACHE);
  await Promise.all(expired.map(async (key) => {
    await Promise.all([cache.delete(key), meta.delete(metadataRequest(key))]);
  }));
};

const metadataRequest = (request) => new Request(
  self.location.origin + '/__svgmap_cache_meta__?url=' + encodeURIComponent(request.url)
);

const store = async (cacheName, request, response, maximum) => {
  if (!(response.ok || response.type === 'opaque')) return;
  const cache = await caches.open(cacheName);
  await cache.put(request, response.clone());
  const meta = await caches.open(META_CACHE);
  await meta.put(metadataRequest(request), new Response(new Date().toISOString()));
  void trimEntries(cacheName, maximum);
};

const storedAt = async (request) => {
  const meta = await caches.open(META_CACHE);
  return (await meta.match(metadataRequest(request)))?.text() || null;
};

const fetchWithTimeout = async (request, milliseconds = 7000) => {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), milliseconds);
  try {
    return await fetch(new Request(request, { signal: controller.signal }));
  } finally {
    clearTimeout(timer);
  }
};

const networkFirst = async (request, cacheName, maximum, label, timeout = 7000) => {
  try {
    const response = await fetchWithTimeout(request, timeout);
    if (!response.ok && response.type !== 'opaque') throw new Error('HTTP ' + response.status);
    await store(cacheName, request, response, maximum);
    void notifyClients({ type: 'SVG3_CACHE_FRESH', label });
    return response;
  } catch (error) {
    const cached = await caches.match(request, { cacheName });
    if (!cached) throw error;
    void notifyClients({
      type: 'SVG3_CACHE_FALLBACK',
      label,
      cachedAt: await storedAt(request),
    });
    return cached;
  }
};

const cacheFirst = async (request, cacheName, maximum) => {
  const cached = await caches.match(request, { cacheName });
  if (cached) return cached;
  const response = await fetch(request);
  await store(cacheName, request, response, maximum);
  return response;
};

const isTile = (url) => [
  'tile.openstreetmap.org',
  'a.tile.openstreetmap.org',
  'b.tile.openstreetmap.org',
  'c.tile.openstreetmap.org',
  'tile.openstreetmap.jp',
  'cyberjapandata.gsi.go.jp',
  'disaportal.gsi.go.jp',
  'disaportaldata.gsi.go.jp',
].includes(url.hostname) && /\\.(png|jpg|jpeg|webp|gif|pbf)$/.test(url.pathname.toLowerCase());

self.addEventListener('install', (event) => {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('svgmap-shell-') || name.startsWith('svgmap-runtime-')) {
        await caches.delete(name);
      }
    }
    await self.clients.claim();
    void notifyClients({ type: 'SVG3_CACHE_READY', version: VERSION });
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);

  if (request.mode === 'navigate') {
    // Never serve an older HTML shell with a different set of JS/SVG assets.
    return;
  }

  // API responses with private/live upstream data or their own explicit HTTP
  // cache policy must never enter the Service Worker's stale runtime cache.
  // Each route remains responsible for browser/CDN cache headers.
  if (url.origin === self.location.origin &&
    (url.pathname === '/api/private-sheet-csv'
      || url.pathname === '/api/private-sheet-image'
      || url.pathname === '/api/cors-proxy'
      || url.pathname === '/api/chugoku-outages')) {
    event.respondWith(fetch(request));
    return;
  }

  if (request.url === GAS_CSV_URL) {
    event.respondWith(networkFirst(request, DYNAMIC_CACHE, MAX_DYNAMIC_ENTRIES, 'GAS CSV'));
    return;
  }

  if (url.origin !== self.location.origin) {
    if (isTile(url)) event.respondWith(cacheFirst(request, TILE_CACHE, MAX_TILE_ENTRIES));
    return;
  }

  if (url.pathname === '/api/drive-image') {
    event.respondWith(networkFirst(request, DYNAMIC_CACHE, MAX_DYNAMIC_ENTRIES, 'Google Drive写真'));
    return;
  }

  if (url.pathname.includes('/svgmapAppLayers/appLayers/okayamaLandslideCandidates/geometry/')
    || url.pathname.endsWith('/svgmapAppLayers/appLayers/okayamaLandslideCandidates/candidates.json')) {
    event.respondWith(networkFirst(request, DYNAMIC_CACHE, MAX_DYNAMIC_ENTRIES, '岡山県土砂災害レイヤー', 30000));
    return;
  }

  if (url.pathname === '/svgmapAppLayers/appLayers/svg3-bosai/team-activity/map/layers/portable/team-activity/current.csv') {
    event.respondWith(networkFirst(request, DYNAMIC_CACHE, MAX_DYNAMIC_ENTRIES, 'チーム活動CSV'));
    return;
  }

  // All other same-origin assets, including app code and SVG documents, use
  // the browser's normal HTTP revalidation instead of stale SW responses.
});
`

fs.writeFileSync(path.join(root, 'sw.js'), sw, 'utf8')
console.log(`[upstream-sw] ${version}: dynamic data and map tiles only; app shell is network-only`)
