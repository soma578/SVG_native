def encode(rows):
    """8x8 rows of colour indices -> 16 bytes in NES 2bpp planar format."""
    lo, hi = [], []
    for row in rows:
        a = b = 0
        for ch in row:
            c = 0 if ch == "." else int(ch)
            a = (a << 1) | (c & 1)
            b = (b << 1) | (c >> 1)
        lo.append(a)
        hi.append(b)
    return bytes(lo + hi)


def main(out):
    chr_rom = bytearray(8192)
    for ch, glyph in FONT.items():
        rows = ["." + r.replace("0", ".") + ".." for r in glyph.split()] + ["........"]
        chr_rom[ord(ch) * 16:ord(ch) * 16 + 16] = encode(rows)
    for tile, art in ART.items():
        if len(art) == 16:  # split 16x16 into TL, TR, BL, BR
            parts = [[r[:8] for r in art[:8]], [r[8:] for r in art[:8]],
                     [r[:8] for r in art[8:]], [r[8:] for r in art[8:]]]
        else:
            parts = [art]
        for i, part in enumerate(parts):
            t = tile + i
            chr_rom[t * 16:t * 16 + 16] = encode(part)
    open(out, "wb").write(chr_rom)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "chr.bin")
